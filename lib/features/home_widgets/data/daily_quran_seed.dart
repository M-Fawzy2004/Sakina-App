  static WidgetQuranData getTodayVerse([DateTime? time]) {
    final now = time ?? DateTime.now();
    final dayOfYear = now.difference(DateTime(now.year, 1, 1)).inDays;
    final index = dayOfYear.abs() % verses.length;
    return verses[index];
  }
